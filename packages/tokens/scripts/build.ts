function shadcnCss(scheme: Flat[], base: Flat[]): string {
  const names = new Set([...scheme, ...base].map((t) => t.name));
  const missing = Object.values(SHADCN_SLOTS).filter((n) => !names.has(`hds-${n}`));
  if (missing.length)
    throw new Error(`shadcn slot targets missing from tokens: ${missing.join(', ')}`);
  const body = Object.entries(SHADCN_SLOTS)
    .map(([slot, n]) => `  --${slot}: var(--hds-${n});`)
    .join('\n');
  return `${HEADER}:root, :host {\n${body}\n}\n`;
}

const out = root + 'dist/';
mkdirSync(out, { recursive: true });
const omni = await themeCss('omni');
writeFileSync(out + 'tokens.css', omni.css);
writeFileSync(out + 'theme.css', tailwindTheme(omni.light, omni.base));
writeFileSync(out + 'shadcn.css', shadcnCss(omni.light, omni.base));

const darkByName = new Map(omni.dark.map((t) => [t.name, t]));
const list = [
  ...omni.base.map((t) => ({
    name: t.path.join('/'),
    cssVar: `--${t.name}`,
    group: t.path[0],
    value: t.value,
    alias: t.alias,
  })),
  ...omni.light.map((t) => ({
    name: t.path.join('/'),
    cssVar: `--${t.name}`,
    group: t.path[0],
    light: t.value,
    dark: darkByName.get(t.name)?.value,
    alias: t.alias,
    darkAlias: darkByName.get(t.name)?.alias,
  })),
].sort((a, b) => a.name.localeCompare(b.name));
writeFileSync(out + 'tokens.json', stableJson(list));
writeFileSync(
  out + 'tokens.ts',
  `${HEADER}export const tokenNames = ${JSON.stringify(
    list.map((t) => t.name),
    null,
    2,
  )} as const;\n` +
    'export type TokenName = (typeof tokenNames)[number];\n' +
    "/** `cssVar('background/neutral/soft')` → `var(--hds-background-neutral-soft)` */\n" +
    "export const cssVar = (name: TokenName): string => `var(--hds-${name.replaceAll('/', '-')})`;\n",
);
console.log(`tokens: ${omni.base.length} base + ${omni.light.length} scheme tokens → dist/`);
