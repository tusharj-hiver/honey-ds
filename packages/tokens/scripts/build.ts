/**
 * Builds dist/ from figma/*.tokens.json (+ manual/*.tokens.json) with Style Dictionary v5.
 *
 * One theme, Omni: HOT primitives + plain Light/Dark semantics + Omni components (C1). The other
 * Figma modes (HIG, Hot - Light/Dark) stay in figma/ but are not built.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import StyleDictionary from 'style-dictionary';
import { stableJson, THEMES, type DtcgTree } from './lib.ts';

export { THEMES };

const root = new URL('..', import.meta.url).pathname;
const read = (rel: string): DtcgTree => JSON.parse(readFileSync(root + rel, 'utf8'));

type ThemeName = keyof typeof THEMES;
type Scheme = 'light' | 'dark';

/** Groups that never change with light/dark (primitives, numeric, manual layout). */
const BASE_GROUPS = new Set([
  'color',
  'scale',
  'font-size',
  'font-weight',
  'font-family',
  'line-height',
  'letter-spacing',
  'spacing',
  'radius',
  'border-width',
  'opacity',
  'layout',
  'effect-size',
  'elevation',
]);

function deepMerge(target: DtcgTree, src: DtcgTree): DtcgTree {
  for (const [k, v] of Object.entries(src)) {
    const cur = target[k];
    if (cur && !('$value' in cur) && v && !('$value' in v))
      deepMerge(cur as DtcgTree, v as DtcgTree);
    else if (cur) throw new Error(`Token defined twice across collections: ${k}`);
    else target[k] = structuredClone(v);
  }
  return target;
}

function tokensFor(theme: ThemeName, scheme: Scheme): DtcgTree {
  const t = THEMES[theme];
  const manual = readdirSync(root + 'manual').filter((f) => f.endsWith('.tokens.json'));
  return [
    `figma/primitives.${t.primitives}.tokens.json`,
    'figma/numeric.Default.tokens.json',
    `figma/semantic.${t.semantic[scheme]}.tokens.json`,
    `figma/components.${t.components}.tokens.json`,
    ...manual.map((f) => `manual/${f}`),
  ].reduce<DtcgTree>((acc, rel) => deepMerge(acc, read(rel)), {});
}

StyleDictionary.registerTransform({
  name: 'name/hds',
  type: 'name',
  // Figma names are kept as-is: `border-width/18` (1.33px) is used for button borders and icon strokes.
  transform: (token) => ['hds', ...token.path].join('-'),
});
StyleDictionary.registerTransform({
  name: 'hds/fontFamily',
  type: 'value',
  filter: (token) => (token.$type ?? token.type) === 'fontFamily',
  transform: (token) => {
    const v = String(token.$value ?? token.value);
    const generic = v.includes('Mono')
      ? 'ui-monospace, monospace'
      : 'ui-sans-serif, system-ui, sans-serif';
    // Self-hosted @fontsource-variable faces register as "<Family> Variable".
    return `"${v}", "${v} Variable", ${generic}`;
  },
});

type Flat = { name: string; path: string[]; value: string; alias?: string };

async function render(theme: ThemeName, scheme: Scheme, part: 'base' | 'scheme', selector: string) {
  const sd = new StyleDictionary({
    tokens: tokensFor(theme, scheme),
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: {
        transforms: ['name/hds', 'hds/fontFamily'],
        files: [
          {
            destination: 'x.css',
            format: 'css/variables',
            filter: (token) => BASE_GROUPS.has(token.path[0]!) === (part === 'base'),
            options: { selector, outputReferences: true, showFileHeader: false },
          },
        ],
      },
    },
  });
  const [file] = await sd.formatPlatform('css');
  const flat: Flat[] = (await sd.getPlatformTokens('css')).allTokens
    .filter((tk) => BASE_GROUPS.has(tk.path[0]!) === (part === 'base'))
    .map((tk) => ({
      name: tk.name,
      path: tk.path,
      value: String(tk.$value),
      ...(typeof tk.original.$value === 'string' && tk.original.$value.startsWith('{')
        ? { alias: tk.original.$value.slice(1, -1) }
        : {}),
    }));
  return { css: String(file!.output).trim(), flat };
}

const indent = (css: string) =>
  css
    .split('\n')
    .map((l) => `  ${l}`)
    .join('\n');
const HEADER =
  '/* Generated by @honey-ds/tokens (scripts/build.ts) from figma/*.tokens.json. Do not edit. */\n';

async function themeCss(theme: ThemeName) {
  const base = await render(theme, 'light', 'base', ':root, :host');
  const light = await render(theme, 'light', 'scheme', ':root, :host, [data-theme="light"]');
  const dark = await render(
    theme,
    'dark',
    'scheme',
    ':root[data-theme="dark"], [data-theme="dark"], :host([data-theme="dark"])',
  );
  const auto = await render(
    theme,
    'dark',
    'scheme',
    ':root:not([data-theme]), :host(:not([data-theme]))',
  );
  const css =
    `${HEADER}${base.css}\n\n${light.css}\n\n${dark.css}\n` +
    `\n@media (prefers-color-scheme: dark) {\n${indent(auto.css)}\n}\n`;
  return { css, base: base.flat, light: light.flat, dark: dark.flat };
}

// ---- Tailwind v4 theme: one utility namespace per role, Tailwind's default palette removed ----
function tailwindTheme(scheme: Flat[], base: Flat[]): string {
  const lines = [
    '--color-*: initial;',
    '--radius-*: initial;',
    '--font-*: initial;',
    '--shadow-*: initial;',
    '--text-*: initial;',
    '--leading-*: initial;',
    '--font-weight-*: initial;',
    '--spacing: 0.25rem; /* Figma spacing/N = N × 4px = Tailwind N (16px root) */',
  ];
  const v = (t: Flat) => `var(--${t.name})`;
  const rest = (t: Flat) => t.path.slice(1).join('-');
  for (const t of scheme) {
    const [group] = t.path;
    if (group === 'background') lines.push(`--background-color-${rest(t)}: ${v(t)};`);
    else if (group === 'text') lines.push(`--text-color-${rest(t)}: ${v(t)};`);
    else if (group === 'border') {
      lines.push(
        `--border-color-${rest(t)}: ${v(t)};`,
        `--divide-color-${rest(t)}: ${v(t)};`,
        `--outline-color-${rest(t)}: ${v(t)};`,
      );
    } else if (group === 'foreground') {
      lines.push(
        `--fill-${rest(t)}: ${v(t)};`,
        `--stroke-${rest(t)}: ${v(t)};`,
        `--text-color-fg-${rest(t)}: ${v(t)};`,
      );
    } else if (group === 'charts') lines.push(`--color-chart-${rest(t)}: ${v(t)};`);
    else if (group === 'effect') lines.push(`--ring-color-${t.path.slice(2).join('-')}: ${v(t)};`);
    else if (COMPONENT_UTILITIES[t.path.join('/')]) {
      for (const ns of COMPONENT_UTILITIES[t.path.join('/')]!) lines.push(`--${ns}: ${v(t)};`);
    }
  }
  for (const t of base) {
    const [group] = t.path;
    if (group === 'radius') lines.push(`--radius-${rest(t)}: ${v(t)};`);
    else if (group === 'font-family') lines.push(`--font-${rest(t)}: ${v(t)};`);
    else if (group === 'font-size') lines.push(`--text-${rest(t)}: ${v(t)};`);
    else if (group === 'line-height') lines.push(`--leading-${rest(t)}: ${v(t)};`);
    else if (group === 'font-weight') lines.push(`--font-weight-${rest(t)}: ${v(t)};`);
    else if (group === 'border-width') lines.push(`--border-w-${rest(t)}: ${v(t)};`);
    // Figma effect styles elevation/xs…xl (manual: not Variables yet) → shadow-xs … shadow-xl.
    else if (group === 'elevation') lines.push(`--shadow-${rest(t)}: ${v(t)};`);
  }
  const utilities = [
    '/* border-w-18 → border-width: var(--hds-border-width-18) (1.33px). Figma names, not Tailwind px steps. */',
    '@utility border-w-* {\n  border-width: --value(--border-w-*);\n}',
    '/* Figma focus effect: 0 0 0 <focus-width> <ring colour>. */',
    '@utility focus-ring {\n  box-shadow: 0 0 0 var(--hds-effect-size-focus) var(--hds-focus-ring);\n}',
    '@utility focus-ring-brand {\n  box-shadow: 0 0 0 var(--hds-effect-size-focus) var(--hds-focus-ring-brand);\n}',
    '@utility focus-ring-error {\n  box-shadow: 0 0 0 var(--hds-effect-size-focus) var(--hds-effect-focus-error);\n}',
  ];
  return `${HEADER}@theme inline {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n\n${utilities.join('\n\n')}\n`;
}

/** Component tokens (components.*.tokens.json) exposed as utilities, e.g. bg-button, text-link. */
