/**
 * svg/<category>/*.svg → src/generated/<Name>.tsx + index + manifest.
 *
 * Colour rules follow hiver-ui-kit's rollup SVGR config (C21): line icons fold every colour to
 * currentColor (#404040 is a stroke in 1,280 places and a fill in 3); hiver-golden icons fold only
 * #404040 and keep their brand fills.
 */
import { transform } from '@svgr/core';
import jsx from '@svgr/plugin-jsx';
import svgo from '@svgr/plugin-svgo';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Config as SvgoConfig } from 'svgo';

const here = new URL('..', import.meta.url).pathname;
const out = join(here, 'src/generated');
const names: Record<string, string> = JSON.parse(readFileSync(join(here, 'names.json'), 'utf8'));

const svgoConfig = (brand: boolean): SvgoConfig => ({
  plugins: [
    { name: 'preset-default', params: { overrides: { removeViewBox: false } } },
    { name: 'removeDimensions' },
    { name: 'prefixIds' },
    { name: 'convertColors', params: { currentColor: brand ? /^#404040$/i : true } },
  ],
});

// React 19: ref is a regular prop, so no forwardRef wrapper is needed.
const template = (
  { componentName, jsx: body }: { componentName: string; jsx: unknown },
  { tpl }: { tpl: (s: TemplateStringsArray, ...v: unknown[]) => unknown },
) => tpl`
import { useId } from 'react';
import type { IconProps } from '../types';

const ${componentName} = ({ size = 20, title, ...props }: IconProps) => {
  const titleId = useId();
  return ${body};
};

export default ${componentName};
`;

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const manifest: { name: string; category: string; keywords: string[]; brand: boolean }[] = [];
const seen = new Set<string>();
for (const category of readdirSync(join(here, 'svg')).sort()) {
  for (const file of readdirSync(join(here, 'svg', category))
    .filter((f) => f.endsWith('.svg'))
    .sort()) {
    const name = names[`${category}/${file}`];
    if (!name) throw new Error(`No component name for ${category}/${file} — rerun import-from-kit`);
    if (seen.has(name)) throw new Error(`Duplicate icon name ${name}`);
    seen.add(name);
    const brand = category === 'hiver-golden';
    const code = await transform(
      readFileSync(join(here, 'svg', category, file), 'utf8'),
      {
        plugins: [svgo, jsx],
        typescript: true,
        titleProp: true,
        svgoConfig: svgoConfig(brand),
        svgProps: {
          width: '{size}',
          height: '{size}',
          'aria-hidden': '{title ? undefined : true}',
          focusable: 'false',
        },
        expandProps: 'end',
        template: template as never,
      },
      { componentName: name },
    );
    writeFileSync(
      join(out, `${name}.tsx`),
      `// Generated by @honey-ds/icons (scripts/generate.ts). Do not edit.\n${code}`,
    );
    manifest.push({ name, category, keywords: file.replace(/\.svg$/, '').split(/[-_]/), brand });
  }
}
writeFileSync(
  join(out, 'index.ts'),
  `// Generated by @honey-ds/icons (scripts/generate.ts). Do not edit.\n${manifest.map((m) => `export { default as ${m.name} } from './${m.name}';`).join('\n')}\n`,
);
writeFileSync(join(out, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(
  `icons: generated ${manifest.length} components (${manifest.filter((m) => m.brand).length} brand)`,
);
